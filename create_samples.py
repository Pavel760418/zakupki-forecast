# Пустой маркер пакета calculations уже есть; для samples — генератор демо-данных
"""Генерация демо Excel для проверки модуля."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

SAMPLES = Path(__file__).resolve().parent


def create_samples() -> None:
    stock = pd.DataFrame(
        {
            "Артикул": ["A-001", "A-002", "A-003", "B-010", "C-100", "C-200"],
            "Наименование": [
                "Молоко ультрапастеризованное 3,2% 1л (длинное наименование для проверки переноса строк без обрезания)",
                "Хлеб пшеничный нарезка 500г",
                "Куриное филе охлаждённое 1кг",
                "Соус томатный для пиццы 2кг ведро",
                "Специи смесь прованских трав 50г",
                "Салфетки бумажные белые 100шт упаковка",
            ],
            "Остаток": [12, 40, 5, 80, 25, 120],
            "Ед. изм.": ["л", "шт", "кг", "кг", "шт", "уп"],
            "Склад": ["Основной"] * 6,
        }
    )

    # Продажи за июнь 2026
    rows = []
    base = {
        "A-001": (2.0, "Молоко ультрапастеризованное 3,2% 1л (длинное наименование для проверки переноса строк без обрезания)"),
        "A-002": (3.0, "Хлеб пшеничный нарезка 500г"),
        "A-003": (1.5, "Куриное филе охлаждённое 1кг"),
        "B-010": (0.8, "Соус томатный для пиццы 2кг ведро"),
        "C-100": (0.1, "Специи смесь прованских трав 50г"),
        # C-200 — почти без продаж (неликвид)
    }
    for day in range(1, 31):
        date = f"2026-06-{day:02d}"
        for sku, (qty, name) in base.items():
            # Вторая половина месяца — рост для A-001 и A-003
            factor = 1.4 if day >= 16 and sku in ("A-001", "A-003") else 1.0
            rows.append(
                {
                    "Артикул": sku,
                    "Наименование": name,
                    "Дата": date,
                    "Количество": round(qty * factor, 2),
                    "Сумма": round(qty * factor * 100, 2),
                }
            )
    # Редкая продажа специй
    rows.append(
        {
            "Артикул": "C-100",
            "Наименование": "Специи смесь прованских трав 50г",
            "Дата": "2026-06-02",
            "Количество": 1,
            "Сумма": 50,
        }
    )

    sales = pd.DataFrame(rows)
    stock_path = SAMPLES / "остатки_демо.xlsx"
    sales_path = SAMPLES / "продажи_демо.xlsx"
    stock.to_excel(stock_path, index=False)
    sales.to_excel(sales_path, index=False)
    print(stock_path)
    print(sales_path)


if __name__ == "__main__":
    create_samples()
